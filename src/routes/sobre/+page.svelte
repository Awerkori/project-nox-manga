  <span class="eyebrow">PROJECT NOX</span>
  <h1>Histórias que ficam com você.</h1>
  <p>
    A Project Nox reúne pessoas apaixonadas por mangás, manhwas e webtoons. Este é o espaço de leitura e
    publicação da nossa comunidade.
  </p>
  <h2>Cuidado em cada página</h2>
  <p>
    Os capítulos passam pela equipe editorial antes de chegar ao catálogo. Tradução, preparação e revisão
    acontecem nos bastidores; o leitor recebe o material final.
  </p>
  <h2>Leia do seu jeito</h2>
  <p>
    Organize sua biblioteca, marque suas histórias favoritas e continue de onde parou. O leitor permite
    ajustar a largura e separar páginas tradicionais.
  </p>
  <h2>Uma comunidade feita de respeito</h2>
  <p>
    Compartilhe suas impressões, sinalize spoilers e respeite outros leitores e criadores. Comentários
    abusivos podem ser removidos pela administração.
  </p>
