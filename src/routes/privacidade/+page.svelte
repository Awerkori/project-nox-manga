  <span class="eyebrow">SEU ESPAÇO, SEUS DADOS</span>
  <h1>Privacidade</h1>
  <p>
    Ao criar uma conta, seu e-mail e sua senha são tratados pelo Supabase Auth. Seu e-mail não aparece no
    perfil público. A aplicação não armazena sua senha em texto puro.
  </p>
  <h2>O que fica salvo</h2>
  <p>
    Seu perfil público contém username, nome de exibição, bio, XP e data de entrada. Biblioteca, favoritos,
    histórico e notificações ficam associados à sua conta e são visíveis apenas para você nas telas pessoais.
    Comentários e curtidas são públicos.
  </p>
  <h2>Sessão e preferências</h2>
  <p>
    Usamos cookies para manter sua sessão e armazenamento local para preferências do leitor e progresso neste
    dispositivo. Não usamos publicidade comportamental ou cookies de anúncios.
  </p>
  <h2>Serviços envolvidos</h2>
  <p>
    Supabase processa contas e dados. Cloudflare hospeda a aplicação quando publicada. As páginas das obras
    são entregues pelo servidor, usando o provedor de armazenamento configurado pela equipe. A tipografia é
    carregada do Google Fonts.
  </p>
  <h2>Segurança e moderação</h2>
  <p>
    Ações administrativas são registradas para auditoria. A equipe pode moderar comentários e suspender contas
    abusivas. As permissões são verificadas no servidor e no banco de dados.
  </p>
  <p>Esta página descreve o funcionamento atual da plataforma e será atualizada quando ele mudar.</p>
