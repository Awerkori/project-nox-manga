  <span class="eyebrow">SEU ESPAO, SEUS DADOS</span>
  <h1>Privacidade</h1>
  <p>
    Ao criar uma conta, seu e-mail e sua senha so tratados pelo Supabase Auth. Seu e-mail no aparece no
    perfil pblico. A aplicao no armazena sua senha em texto puro.
  </p>
  <h2>O que fica salvo</h2>
  <p>
    Seu perfil pblico contm username, nome de exibio, bio, XP e data de entrada. Biblioteca, favoritos,
    histrico e notificaes ficam associados  sua conta e so visveis apenas para voc nas telas pessoais.
    Comentrios e curtidas so pblicos.
  </p>
  <h2>Sesso e preferncias</h2>
  <p>
    Usamos cookies para manter sua sesso e armazenamento local para preferncias do leitor e progresso neste
    dispositivo. No usamos publicidade comportamental ou cookies de anncios.
  </p>
  <h2>Servios envolvidos</h2>
  <p>
    Supabase processa contas e dados. Cloudflare hospeda a aplicao quando publicada. As pginas das obras
    so entregues pelo servidor, usando o provedor de armazenamento configurado pela equipe. A tipografia 
    carregada do Google Fonts.
  </p>
  <h2>Segurana e moderao</h2>
  <p>
    Aes administrativas so registradas para auditoria. A equipe pode moderar comentrios e suspender contas
    abusivas. As permisses so verificadas no servidor e no banco de dados.
  </p>
  <p>Esta pgina descreve o funcionamento atual da plataforma e ser atualizada quando ele mudar.</p>
